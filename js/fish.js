window.fishes = fishes;
let currentPage = 1;

const fishesPerPage = 7;

let filteredFishes = [...fishes];

const animalsContainer =
document.getElementById("animalsContainer");



function renderFishes(data){

animalsContainer.innerHTML = "";

data.forEach(fish => {

animalsContainer.innerHTML += `

<div class="fish-card">

<img src="${fish.image}" alt="">

<div class="fish-info">

<h3>${fish.name}</h3>

<span class="latin-name">
${fish.latin}
</span>

<p>
${fish.description}
</p>

</div>

<div class="card-right">

<div class="card-tag">
Balıklar
</div>

<a href="animal-detail.html?id=${fish.id}" class="arrow-btn">
→
</a>

</div>

</div>

`;

});

}



function renderPage(page){

currentPage = page;

const start =
(currentPage - 1) * fishesPerPage;

const end =
start + fishesPerPage;

const paginatedFishes =
filteredFishes.slice(start,end);

renderFishes(paginatedFishes);

}



function renderPagination(){

const pageNumbers =
document.getElementById("pageNumbers");

pageNumbers.innerHTML = "";

const totalPages =
Math.ceil(filteredFishes.length / fishesPerPage);

for(let i = 1; i <= totalPages; i++){

pageNumbers.innerHTML += `

<div
class="page-number ${i === currentPage ? "active" : ""}"
onclick="goToPage(${i})">

${i}

</div>

`;

}

}



function goToPage(page){

currentPage = page;

renderPage(currentPage);

renderPagination();

}



const searchInput =
document.getElementById("searchInput");

const popularityBtn =
document.getElementById("popularityBtn");

const sortAZ =
document.getElementById("sortAZ");

const allAnimals =
document.getElementById("allAnimals");



searchInput.addEventListener("input", () => {

const value =
searchInput.value.toLowerCase();

filteredFishes =
fishes.filter(fish =>

fish.name
.toLowerCase()
.includes(value)

);

currentPage = 1;

renderPage(currentPage);

renderPagination();

});



popularityBtn.addEventListener("click", () => {

filteredFishes =
[...fishes].sort(
(a,b) =>
b.popularity - a.popularity
);

currentPage = 1;

renderPage(currentPage);

renderPagination();

});



sortAZ.addEventListener("click", () => {

filteredFishes =
[...fishes].sort(
(a,b) =>
a.name.localeCompare(b.name)
);

currentPage = 1;

renderPage(currentPage);

renderPagination();

});



allAnimals.addEventListener("click", () => {

filteredFishes = [...fishes];

currentPage = 1;

renderPage(currentPage);

renderPagination();

});



renderPage(currentPage);

renderPagination();
