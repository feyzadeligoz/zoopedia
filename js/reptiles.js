window.reptiles = reptiles;

let currentPage = 1;

const reptilesPerPage = 7;

let filteredReptiles = [...reptiles];

const animalsContainer =
document.getElementById("animalsContainer");



function renderReptiles(data){

animalsContainer.innerHTML = "";

data.forEach(reptile => {

animalsContainer.innerHTML += `

<div class="reptile-card">

<img src="${reptile.image}" alt="">

<div class="reptile-info">

<h3>${reptile.name}</h3>

<span class="latin-name">
${reptile.latin}
</span>

<p>
${reptile.description}
</p>

</div>

<div class="card-right">

<div class="card-tag">
Sürüngenler
</div>

<a href="animal-detail.html?id=${reptile.id}" class="arrow-btn">
→
</a>

</div>

</div>

`;

});

}

function renderPage(page){

currentPage = page;

const start =
(currentPage - 1) * reptilesPerPage;

const end =
start + reptilesPerPage;

const paginatedReptiles =
filteredReptiles.slice(start,end);

renderReptiles(paginatedReptiles);

}



function renderPagination(){

const pageNumbers =
document.getElementById("pageNumbers");

pageNumbers.innerHTML = "";

const totalPages =
Math.ceil(filteredReptiles.length / reptilesPerPage);

for(let i = 1; i <= totalPages; i++){

pageNumbers.innerHTML += `

<div
class="page-number ${i === currentPage ? "active" : ""}"
onclick="goToPage(${i})">

${i}

</div>

`;

}

}

function goToPage(page){

currentPage = page;

renderPage(currentPage);

renderPagination();

}
const searchInput =
document.getElementById("searchInput");

const popularityBtn =
document.getElementById("popularityBtn");

const sortAZ =
document.getElementById("sortAZ");

const allAnimals =
document.getElementById("allAnimals");



searchInput.addEventListener("input", () => {

const value =
searchInput.value.toLowerCase();

filteredReptiles =
reptiles.filter(reptile =>

reptile.name
.toLowerCase()
.includes(value)

);

currentPage = 1;

renderPage(currentPage);

renderPagination();

});



popularityBtn.addEventListener("click", () => {

filteredReptiles =
[...reptiles].sort(
(a,b) =>
b.popularity - a.popularity
);

currentPage = 1;

renderPage(currentPage);

renderPagination();

});



sortAZ.addEventListener("click", () => {

filteredReptiles =
[...reptiles].sort(
(a,b) =>
a.name.localeCompare(b.name)
);

currentPage = 1;

renderPage(currentPage);

renderPagination();

});



allAnimals.addEventListener("click", () => {

filteredReptiles = [...reptiles];

currentPage = 1;

renderPage(currentPage);

renderPagination();

});



renderPage(currentPage);

renderPagination();
